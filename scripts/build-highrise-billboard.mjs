// HIGH RISE S5 — THE B1 BILLBOARD (the owner's pick, Downloads\NEON\highrise-billboard-B-v2.png, the TOP one; docs/highrise.md "THE
// BILLBOARD"). scripts/build-jaywalk-billboard.mjs is the pattern:
//   1. THE LETTERING as path data (no font load on the site): HIGH · RISE · OPEN NOW in BOWLBY ONE (JAYWALK's billboard face — Google Fonts,
//      SIL Open Font License 1.1; fetched from GitHub at BUILD time only) → js/games/highrise/billboard-glyphs.js (GENERATED).
//   2. THE POSTER: /highrise-play?poster=1 (poster.js — the real night scene staged the same every time) in a tall viewport (the canvas
//      ≥ 1696 px wide: the 2× crop is never upscaled) → the board at 2× (1696 × 896) + 1× (848 × 448).
//   3. → assets/city/highrise/billboard.webp (the 1× board, its words baked in — JAYWALK's OPEN NOW face is drawn whole the same way) +
//      the PNGs into Downloads\NEON\highrise-s5\billboard\ (or argv[3]). NOT wired into the city: the CITY chat installs it at go-live.
//   node scripts/build-highrise-billboard.mjs "<chromium>" [outDir] [--art-only]     (needs scripts/serve.mjs on :5173)
import fs from 'node:fs';
import { join } from 'node:path';
import { homedir } from 'node:os';
import puppeteer from '../tests/integration/kit/puppeteer.mjs';

const BASE = process.env.E2E_BASE || 'http://localhost:5173';
/** the staged seed (poster.js POSTER.seed — its slabs violet-blue in THE CLOUDS: the mockup's tower) */
const POSTER_SEED = 'poster2';
const OUT = process.argv[3] && !process.argv[3].startsWith('--') ? process.argv[3] : join(homedir(), 'Downloads', 'NEON', 'highrise-s5', 'billboard');
const FONTS = { heavy: 'https://raw.githubusercontent.com/google/fonts/main/ofl/bowlbyone/BowlbyOne-Regular.ttf' };
const WORDS = {
  high: { font: 'heavy', text: 'HIGH', track: 0.02 },
  rise: { font: 'heavy', text: 'RISE', track: 0.02 },
  open: { font: 'heavy', text: 'OPEN NOW', track: 0.1 },
};
const browser = await puppeteer.launch({ executablePath: process.argv[2], headless: true, args: ['--enable-gpu', '--use-angle=d3d11', '--enable-webgl', '--ignore-gpu-blocklist'] });
// ---- 1. the glyphs (--art-only: kept as they are)
if (!process.argv.includes('--art-only')) {
  const page = await browser.newPage();
  await page.goto(`${BASE}/404.html`);
  await page.addScriptTag({ url: 'https://cdnjs.cloudflare.com/ajax/libs/opentype.js/1.3.4/opentype.min.js' });
  const out = await page.evaluate(async (FONTS, WORDS) => {
    const fonts = {};
    for (const [k, url] of Object.entries(FONTS)) fonts[k] = opentype.parse(await (await fetch(url)).arrayBuffer());
    const res = {};
    for (const [id, w] of Object.entries(WORDS)) {
      const f = fonts[w.font], size = 1000, glyphs = f.stringToGlyphs(w.text);
      let x = 0; const parts = [];
      glyphs.forEach((g, i) => {
        parts.push(g.getPath(x, 0, size).toPathData(1));
        x += g.advanceWidth * size / f.unitsPerEm + (i < glyphs.length - 1 ? w.track * size : 0);
        if (i < glyphs.length - 1) x += f.getKerningValue(g, glyphs[i + 1]) * size / f.unitsPerEm;
      });
      const tmp = new opentype.Path(); tmp.extend(f.getPath(w.text, 0, 0, size)); const b0 = tmp.getBoundingBox();
      res[id] = { d: parts.join(''), w: Math.round(x), cap: Math.round(-b0.y1) };
    }
    return res;
  }, FONTS, WORDS);
  await page.close();
  const lines = Object.entries(out).map(([k, v]) => `  ${k}: { w: ${v.w}, cap: ${v.cap}, d: '${v.d}' },`);
  fs.writeFileSync(new URL('../js/games/highrise/billboard-glyphs.js', import.meta.url), `// GENERATED by scripts/build-highrise-billboard.mjs — never edit by hand. THE B1 BILLBOARD's lettering as SVG path data (1000 units = 1 em,
// the baseline at y 0, cap height \`cap\`, advance \`w\`): HIGH · RISE · OPEN NOW in Bowlby One (Google Fonts, SIL Open Font License 1.1).
export const HI_GLYPHS = Object.freeze({
${lines.join('\n')}
});
`);
  console.log('wrote js/games/highrise/billboard-glyphs.js', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, { w: v.w, cap: v.cap, bytes: v.d.length }])));
}
// ---- 2. the poster (a tall viewport: the stage is 0.6 of the height wide — 900 css × dpr 2 = a 1800 px canvas)
const p = await browser.newPage();
const errs = [];
p.on('pageerror', e => errs.push(String(e.message || e)));
await p.setViewport({ width: 900, height: 1500, deviceScaleFactor: 2 });
await p.goto(`${BASE}/highrise-play?poster=1&seed=${process.env.POSTER_SEED || POSTER_SEED}&floor=78&look=night&tier=2`, { waitUntil: 'load' });
const end = Date.now() + 60000;
let res = null;
while (Date.now() < end && !res) { res = await p.evaluate(() => window.__hiPoster || null).catch(() => null); if (!res) await new Promise(r => setTimeout(r, 200)); }
if (!res) { console.error('the poster never came', errs); await browser.close(); process.exit(1); }
fs.mkdirSync(OUT, { recursive: true });
const png = u => Buffer.from(u.split(',')[1], 'base64');
fs.writeFileSync(join(OUT, 'highrise-billboard-2x.png'), png(res.board2x));
fs.writeFileSync(join(OUT, 'highrise-billboard-1x.png'), png(res.board1x));
fs.writeFileSync(join(OUT, 'highrise-billboard-art-2x.png'), png(res.art2x));
// ---- 3. the city's file: the 1× board as WebP (the browser's own encoder — no tool on the build machine)
const webp = await p.evaluate(async u => { const im = new Image(); im.src = u; await im.decode(); const c = document.createElement('canvas'); c.width = im.width; c.height = im.height; c.getContext('2d').drawImage(im, 0, 0); return c.toDataURL('image/webp', 0.86); }, res.board1x);
fs.mkdirSync(new URL('../assets/city/highrise/', import.meta.url), { recursive: true });
const wb = png(webp);
fs.writeFileSync(new URL('../assets/city/highrise/billboard.webp', import.meta.url), wb);
await browser.close();
console.log(`the frame ${res.frame.w} × ${res.frame.h} (the top at ${res.frame.topY.toFixed(2)}) → ${OUT}: highrise-billboard-2x.png · -1x.png · -art-2x.png · assets/city/highrise/billboard.webp ${(wb.length / 1024).toFixed(1)} KB${errs.length ? ` — page errors: ${errs.join(' | ')}` : ''}`);
