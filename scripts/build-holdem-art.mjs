// CITY FIXES + HOLD'EM — THE HOLD'EM POSTER's LETTERING AS PATHS (dev only; the site loads no font for it): the two Google Fonts (OFL) the
// approved mock uses the look of — HOLD'EM in ALFA SLAB ONE (a vintage slab serif), the bar in POPPINS BOLD — turned into SVG path data ONCE
// (opentype.js in the test browser), so js/screens/harbor/holdem-art.js paints the poster in code, crisp at any size, at once (no font load
// after the city's reveal — no re-bake). Writes js/screens/harbor/holdem-glyphs.js (GENERATED — never edit it by hand).
//   node scripts/build-holdem-art.mjs "<chromium>"
import fs from 'node:fs';
import puppeteer from '../tests/integration/kit/puppeteer.mjs';

const FONTS = {
  slab: 'https://raw.githubusercontent.com/google/fonts/main/ofl/alfaslabone/AlfaSlabOne-Regular.ttf',
  sans: 'https://raw.githubusercontent.com/google/fonts/main/ofl/poppins/Poppins-Bold.ttf',
};
// each word: its font, its text, its tracking (em)
const WORDS = {
  holdem: { font: 'slab', text: 'HOLD’EM', track: 0.0 },
  soon: { font: 'sans', text: 'COMING SOON', track: 0.06 },
  open: { font: 'sans', text: 'NOW OPEN', track: 0.06 },
};

const browser = await puppeteer.launch({ executablePath: process.argv[2], headless: true });
const page = await browser.newPage();
await page.goto('about:blank');
await page.addScriptTag({ url: 'https://cdnjs.cloudflare.com/ajax/libs/opentype.js/1.3.4/opentype.min.js' });
const out = await page.evaluate(async (FONTS, WORDS) => {
  const fonts = {};
  for (const [k, url] of Object.entries(FONTS)) fonts[k] = opentype.parse(await (await fetch(url)).arrayBuffer());
  const res = {};
  for (const [id, w] of Object.entries(WORDS)) {
    const f = fonts[w.font], size = 1000, glyphs = f.stringToGlyphs(w.text);
    let x = 0; const parts = [];
    glyphs.forEach((g, i) => {
      const p = g.getPath(x, 0, size);
      parts.push(p.toPathData(1));
      x += g.advanceWidth * size / f.unitsPerEm + (i < glyphs.length - 1 ? w.track * size : 0);
      if (i < glyphs.length - 1) x += f.getKerningValue(g, glyphs[i + 1]) * size / f.unitsPerEm;
    });
    // the ink's real box (for centring + the cap height)
    const all = f.getPath(w.text, 0, 0, size);
    let bb = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity };
    for (const d of parts) { const pp = new Path2D(d); void pp; }
    const tmp = new opentype.Path(); tmp.extend(all); const b0 = tmp.getBoundingBox();
    bb = { x1: b0.x1, y1: b0.y1, x2: Math.max(b0.x2, x), y2: b0.y2 };
    res[id] = { d: parts.join(''), w: Math.round(x), cap: Math.round(-bb.y1), base: 0, font: w.font };
  }
  return res;
}, FONTS, WORDS);
await browser.close();

const lines = Object.entries(out).map(([k, v]) => `  ${k}: { w: ${v.w}, cap: ${v.cap}, d: '${v.d}' },`);
fs.writeFileSync(new URL('../js/screens/harbor/holdem-glyphs.js', import.meta.url), `// GENERATED by scripts/build-holdem-art.mjs — never edit by hand. THE HOLD'EM POSTER's lettering as SVG path data (1000 units = 1 em,
// the baseline at y 0, cap height \`cap\`, advance \`w\`): HOLD'EM in Alfa Slab One + the bar in Poppins Bold (Google Fonts, SIL Open Font License 1.1).
export const GLYPHS = Object.freeze({
${lines.join('\n')}
});
`);
console.log('wrote js/screens/harbor/holdem-glyphs.js', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, { w: v.w, cap: v.cap, bytes: v.d.length }])));
