// Builds data/oc/make24.json: every set of four tiles 1–9 that can make exactly 24 with + − × ÷,
// split into an EASY and a HARD pool, each with one verified solution for the reveal.
//
//   node scripts/build-make24.mjs
//
// The search is exhaustive (challenges.js#solve24: every pairwise combination, exact fractions).
//   easy = solvable without ever leaving the whole numbers, and with plenty of ways to get there
//   hard = can't be done without dividing (e.g. 3 3 8 8 → 8 ÷ (3 − 8 ÷ 3), 1 3 4 6 → 6 ÷ (1 − 3 ÷ 4)),
//          or has at most 2 routes (and no pair of 1s)
// Sets in the middle are left out so the two puzzles of a challenge feel clearly different.
import { writeFileSync } from 'node:fs';
import { solve24, applyOp } from '../js/games/overclock/challenges.js';

// can these tiles make 24 using only + − × ?
const noDivision = tiles => {
  if (tiles.length === 1) return tiles[0][0] === 24 && tiles[0][1] === 1;
  for (let i = 0; i < tiles.length; i++) for (let j = 0; j < tiles.length; j++) {
    if (i === j) continue;
    for (const op of ['+', '-', '*']) if (noDivision([...tiles.filter((_, k) => k !== i && k !== j), applyOp(tiles[i], op, tiles[j])])) return true;
  }
  return false;
};

const all = [];
for (let a = 1; a <= 9; a++) for (let b = a; b <= 9; b++) for (let c = b; c <= 9; c++) for (let d = c; d <= 9; d++) {
  const r = solve24([a, b, c, d]);
  all.push({ key: `${a}${b}${c}${d}`, ...r, needsDiv: r.count > 0 && !noDivision([a, b, c, d].map(n => [n, 1])) });
}
const solvable = all.filter(r => r.count > 0);
const counts = solvable.map(r => r.count).sort((x, y) => x - y);
const pct = q => counts[Math.floor(q * (counts.length - 1))];
const EASY_MIN = pct(0.5); // at least as many solutions as the median set
const HARD_MAX = 2;
const easy = solvable.filter(r => r.intCount > 0 && r.count >= EASY_MIN && !/1.*1.*1/.test(r.key));
const hard = solvable.filter(r => r.needsDiv || (r.count <= HARD_MAX && !/1.*1/.test(r.key)));
const row = r => [r.key, r.expr];
writeFileSync('data/oc/make24.json', `${JSON.stringify({
  note: 'Generated by scripts/build-make24.mjs — every set verified solvable. [tiles, one solution]',
  easy: easy.map(row),
  hard: hard.map(row),
})}\n`);
console.log(`${all.length} sets, ${solvable.length} solvable; easy ${easy.length} (≥ ${EASY_MIN} solutions), hard ${hard.length} (division needed: ${hard.filter(r => r.needsDiv).length}, ≤ ${HARD_MAX} routes)`);
console.log('hard samples:', hard.slice(0, 12).map(r => `${r.key}: ${r.expr}`).join(' | '));
